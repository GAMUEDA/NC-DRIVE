// Rebuilds js/nest-admin8-src.js from nest_admin_8.html (run after replacing that file with a newer version):
//   node tools/embed-nest-admin.js
// The page is kept byte-for-byte as a JS string so index.html can run it in a same-origin frame even from file://,
// where a plain <iframe src> would be a separate origin that the main page cannot size or theme.
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'nest_admin_8.html'), 'utf8');
const out = '/* GENERATED by tools/embed-nest-admin.js from nest_admin_8.html. Do not edit; replace nest_admin_8.html and rerun. */\n'
  + 'window.NEST_ADMIN8_HTML = ' + JSON.stringify(html) + ';\n';
fs.writeFileSync(path.join(root, 'js', 'nest-admin8-src.js'), out);
console.log('js/nest-admin8-src.js written (' + html.length + ' chars)');
